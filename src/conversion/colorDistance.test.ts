describe('CIEDE2000 · Sharma 34 组门禁', () => {
  it('34 组参考向量全部在 1e-4 以内', () => {
    const failures: string[] = []
    SHARMA.forEach(([lab1, lab2, expected], i) => {
      const got = ciede2000(lab1, lab2)
      if (Math.abs(got - expected) > 1e-4) {
        failures.push(`#${i + 1} 期望 ${expected}，得到 ${got.toFixed(6)}`)
      }
    })
    expect(failures).toEqual([])
  })

  it('对称：换两个参数的位置结果一样', () => {
    for (const [a, b] of SHARMA) expect(ciede2000(a, b)).toBeCloseTo(ciede2000(b, a), 12)
  })

  it('自比必为 0', () => {
    for (const [a] of SHARMA) expect(ciede2000(a, a)).toBe(0)
  })
})

describe('色彩空间换算', () => {
  it('sRGB ↔ linear 互逆', () => {
    for (const c of [0, 1, 12, 64, 128, 200, 254, 255]) {
      const back = Math.round(
        (srgbToLinear(c) <= 0.0031308
          ? srgbToLinear(c) * 12.92
          : 1.055 * Math.pow(srgbToLinear(c), 1 / 2.4) - 0.055) * 255,
      )
      expect(back).toBe(c)
    }
    expect(linearToRgb([0, 0, 0])).toEqual([0, 0, 0])
  })

  it('linear 映射两端正确', () => {
    expect(srgbToLinear(0)).toBe(0)
    expect(srgbToLinear(255)).toBeCloseTo(1, 10)
    expect(srgbToLinear(128)).toBeCloseTo(0.2158605, 6)
  })

  it('白黑灰的 Lab', () => {
    const white = rgbToLab([255, 255, 255])
    expect(white[0]).toBeCloseTo(100, 3)
    expect(white[1]).toBeCloseTo(0, 3)
    expect(white[2]).toBeCloseTo(0, 3)
    expect(rgbToLab([0, 0, 0])).toEqual([0, 0, 0])
    const gray = rgbToLab([128, 128, 128])
    expect(gray[0]).toBeCloseTo(53.585, 2)
    expect(gray[1]).toBeCloseTo(0, 3)
    expect(gray[2]).toBeCloseTo(0, 3)
  })

  it('原色的 Lab 与公开数据一致', () => {
    const red = rgbToLab([255, 0, 0])
    expect(red[0]).toBeCloseTo(53.2408, 3)
    expect(red[1]).toBeCloseTo(80.0925, 3)
    expect(red[2]).toBeCloseTo(67.2032, 3)
    const blue = rgbToLab([0, 0, 255])
    expect(blue[0]).toBeCloseTo(32.297, 3)
    expect(blue[1]).toBeCloseTo(79.1875, 3)
    expect(blue[2]).toBeCloseTo(-107.8602, 3)
  })

  it('Oklab：白 1/黑 0/灰接近 0.6', () => {
    expect(rgbToOklab([255, 255, 255])[0]).toBeCloseTo(1, 6)
    expect(rgbToOklab([0, 0, 0])[0]).toBeCloseTo(0, 9)
    expect(rgbToOklab([128, 128, 128])[0]).toBeCloseTo(0.59987, 4)
    expect(rgbToOklab([128, 128, 128])[1]).toBeCloseTo(0, 6)
  })
})
